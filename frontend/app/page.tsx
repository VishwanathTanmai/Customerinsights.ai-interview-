"use client";
import { useCallback, useEffect, useMemo, useState } from "react";
import { api, HcpRow, logEvent, Territory } from "@/lib/api";
import { useRep } from "@/lib/rep";
import HcpPanel from "@/components/HcpPanel";

type ListResp = { week: string | null; total: number; flagged_cutoff: number; items: HcpRow[] };
type Meta = { territories: Territory[]; regions: string[]; specialties: string[] };
const PAGE = 50;

export default function CallList() {
  const [rep] = useRep();
  const [meta, setMeta] = useState<Meta | null>(null);
  const [f, setF] = useState({ region: "", territory: "", specialty: "", rep: "", q: "", sort: "uplift", flagged_only: true });
  const [offset, setOffset] = useState(0);
  const [data, setData] = useState<ListResp | null>(null);
  const [err, setErr] = useState("");
  const [loading, setLoading] = useState(true);
  const [sel, setSel] = useState<string | null>(null);

  useEffect(() => { api<Meta>("/territories").then(setMeta).catch(e => setErr(String(e))); }, []);
  useEffect(() => { if (rep) logEvent(rep, "list_open"); }, [rep]);

  // Default the territory filter to the acting rep's territory
  useEffect(() => {
    if (!rep || !meta) return;
    const t = meta.territories.find(t => t.rep_id === rep);
    if (t) setF(p => ({ ...p, rep: rep, territory: t.territory_id, region: t.region }));
  }, [rep, meta]);

  const query = useMemo(() => {
    const p = new URLSearchParams();
    Object.entries(f).forEach(([k, v]) => { if (v !== "" && v !== undefined) p.set(k, String(v)); });
    p.set("limit", String(PAGE)); p.set("offset", String(offset));
    return p.toString();
  }, [f, offset]);

  const load = useCallback(() => {
    setLoading(true);
    api<ListResp>(`/hcps?${query}`).then(d => { setData(d); setErr(""); }).catch(e => setErr(String(e))).finally(() => setLoading(false));
  }, [query]);
  useEffect(() => { load(); }, [load]);
  // live refresh so other reps' feedback and new scoring runs appear without reload
  useEffect(() => { const id = setInterval(load, 20000); return () => clearInterval(id); }, [load]);

  const set = (k: string, v: string | boolean) => { setOffset(0); setF(p => ({ ...p, [k]: v })); if (rep) logEvent(rep, "filter_change"); };
  const terrs = (meta?.territories || []).filter(t => !f.region || t.region === f.region);
  const items = data?.items || [];
  const newCount = items.filter(i => i.call_status === "New").length;

  return (
    <>
      <section className="hero">
        <div>
          <h1>This week&apos;s <span className="grad">high-uplift</span> call list</h1>
          <p>HCPs ranked by the <b>incremental</b> TRx a visit is expected to add, not by who already prescribes. Each reason is generated by Mistral and checked against the HCP&apos;s own data.</p>
        </div>
        <div className="row small muted"><span className="live" aria-hidden /> Live from Postgres · week {data?.week || "—"}</div>
      </section>

      <div className="kpis">
        <div className="card kpi"><div className="label">HCPs in view</div><div className="value">{data?.total ?? "—"}</div><div className="sub">{f.flagged_only ? `flagged top ${data?.flagged_cutoff ?? ""}` : "full universe"}</div></div>
        <div className="card kpi"><div className="label">New vs usual (page)</div><div className="value">{items.length ? Math.round(newCount / items.length * 100) : 0}%</div><div className="sub">not visited 3+ times in 12 months</div></div>
        <div className="card kpi"><div className="label">Feedback given (page)</div><div className="value">{items.filter(i => i.last_feedback).length}</div><div className="sub">of {items.length} shown</div></div>
      </div>

      <div className="filters card" role="search">
        <select id="f-region" aria-label="Region" value={f.region} onChange={e => { set("region", e.target.value); set("territory", ""); }}>
          <option value="">All regions</option>{meta?.regions.map(r => <option key={r}>{r}</option>)}
        </select>
        <select id="f-territory" aria-label="Territory" value={f.territory} onChange={e => set("territory", e.target.value)}>
          <option value="">All territories</option>{terrs.map(t => <option key={t.territory_id} value={t.territory_id}>{t.name} ({t.territory_id})</option>)}
        </select>
        <select id="f-specialty" aria-label="Specialty" value={f.specialty} onChange={e => set("specialty", e.target.value)}>
          <option value="">All specialties</option>{meta?.specialties.map(s => <option key={s}>{s}</option>)}
        </select>
        <select id="f-rep" aria-label="Rep" value={f.rep} onChange={e => set("rep", e.target.value)}>
          <option value="">All reps</option>{meta?.territories.map(t => <option key={t.rep_id} value={t.rep_id}>{t.rep_name}</option>)}
        </select>
        <select id="f-sort" aria-label="Sort" value={f.sort} onChange={e => set("sort", e.target.value)}>
          <option value="uplift">Sort: uplift</option><option value="recency">Sort: longest since visit</option>
        </select>
        <input id="f-search" aria-label="Search" placeholder="Search HCP…" value={f.q} onChange={e => set("q", e.target.value)} />
        <label className="row small"><input id="f-flagged" type="checkbox" checked={f.flagged_only} onChange={e => set("flagged_only", e.target.checked)} /> Flagged only</label>
      </div>

      {err && <div className="card" style={{ borderColor: "var(--bad)" }}>Cannot reach API: {err}</div>}

      <div className={`layout ${sel ? "with-panel" : ""}`}>
        <div className="card" style={{ padding: 8 }}>
          <div className="tablewrap">
            <table>
              <thead><tr><th>#</th><th>HCP</th><th>Specialty</th><th>Territory</th><th>Uplift</th><th>Top reason</th><th>Status</th></tr></thead>
              <tbody>
                {loading && !data && Array.from({ length: 8 }).map((_, i) => <tr key={i}><td colSpan={7}><div className="skeleton" /></td></tr>)}
                {items.map(r => (
                  <tr key={r.hcp_id} className={sel === r.hcp_id ? "sel" : ""} tabIndex={0}
                    onClick={() => setSel(r.hcp_id)} onKeyDown={e => e.key === "Enter" && setSel(r.hcp_id)}>
                    <td className="muted">{r.rank}</td>
                    <td><b>{r.display_name}</b><div className="small muted">{r.hcp_id}{r.last_feedback && <> · <span className="badge b-ok">{r.last_feedback.replace("_", " ")}</span></>}</div></td>
                    <td>{r.specialty}</td>
                    <td>{r.territory_name}<div className="small muted">{r.rep_name}</div></td>
                    <td><span className={`badge b-${r.band.toLowerCase()}`}>{r.band}</span><div className="small muted">+{r.uplift.toFixed(2)} TRx/mo</div></td>
                    <td className="reason">{r.reason_text || <span className="muted">Not in reason batch</span>}</td>
                    <td><span className={`badge ${r.call_status === "New" ? "b-new" : "b-usual"}`}>{r.call_status}</span></td>
                  </tr>
                ))}
                {!loading && items.length === 0 && <tr><td colSpan={7} className="empty">No HCPs match. Has the pipeline been run?</td></tr>}
              </tbody>
            </table>
          </div>
          <div className="pager">
            <span className="small muted">{data ? `${offset + 1}–${Math.min(offset + PAGE, data.total)} of ${data.total}` : ""}</span>
            <button id="prev-page" className="ghost" disabled={offset === 0} onClick={() => setOffset(o => Math.max(0, o - PAGE))}>Prev</button>
            <button id="next-page" className="ghost" disabled={!data || offset + PAGE >= data.total} onClick={() => setOffset(o => o + PAGE)}>Next</button>
          </div>
        </div>
        {sel && <HcpPanel hcpId={sel} onClose={() => setSel(null)} onChanged={load} />}
      </div>
    </>
  );
}
